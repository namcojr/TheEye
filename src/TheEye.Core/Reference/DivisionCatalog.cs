    /// <summary>
    /// Human name of a division ("PT" → "Portugal"). An unknown code is echoed
    /// back as it came, so a new division still reads as something.
    /// </summary>
    public static string Name(string? code)
    {
        var normalized = Normalize(code);
        return normalized.Length == 0
            ? string.Empty
            : Countries.TryGetValue(normalized, out var name) ? name : normalized;
    }

    /// <summary>
    /// Flag image of a division, or null when the code is not a country this
    /// catalogue knows: an empty slot looks better than a broken image.
    /// </summary>
    public static string? FlagUrl(string? code)
    {
        var normalized = Normalize(code);
        return normalized.Length == 2 && Countries.ContainsKey(normalized)
            ? FlagBaseAddress + normalized.ToLowerInvariant() + ".png"
            : null;
    }

    /// <summary>Number of countries the catalogue can name, used by the tests.</summary>
    public static int Count => Countries.Count;

    private static string Normalize(string? code) =>
        string.IsNullOrWhiteSpace(code) ? string.Empty : code.Trim().ToUpperInvariant();
